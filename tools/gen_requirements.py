"""Regenerate frontend/src/app/requirements.data.ts from the requirement workbook.

Run from the repository root: python tools/gen_requirements.py
"""
import json, sys
import openpyxl

src = r'docs/LOTUS_PMS_V4_DoiChieu.xlsx'
out = r'frontend/src/app/requirements.data.ts'
ws = openpyxl.load_workbook(src, data_only=True)['Backlog 107 yeu cau']
rows = list(ws.iter_rows(values_only=True))
header = [str(h).strip() if h else '' for h in rows[0]]
keys = {
    'Mã yêu cầu': 'code', 'Nhóm phân hệ': 'group', 'Tên yêu cầu (nguồn)': 'name', 'Ưu tiên nguồn': 'priority',
    'Đánh giá khả thi LOTUS': 'feasibility', 'Hiện trạng LOTUS V4 (đối chiếu mã)': 'v4Status',
    'Đề xuất giai đoạn': 'phase', 'Hướng triển khai LOTUS': 'approach', 'Phụ thuộc / điều kiện': 'dependency',
    'API REST đề xuất': 'api', 'Quy tắc nghiệp vụ nguồn': 'rules', 'Tiêu chí nghiệm thu nguồn': 'acceptance',
}
idx = {keys[h]: i for i, h in enumerate(header) if h in keys}
missing = set(keys.values()) - set(idx)
if missing:
    sys.exit(f'Missing columns: {missing}')

def clean(v):
    return ' '.join(str(v).split()) if v not in (None, '') else ''

items = []
for r in rows[1:]:
    if not r[idx['code']]:
        continue
    items.append({k: clean(r[i]) for k, i in idx.items()})

body = json.dumps(items, ensure_ascii=False, indent=1)
with open(out, 'w', encoding='utf-8', newline='\n') as f:
    f.write('// Generated by tools/gen_requirements.py from docs/LOTUS_PMS_V4_DoiChieu.xlsx (sheet "Backlog 107 yeu cau"). Do not edit by hand.\n')
    f.write('export interface Requirement { code: string; group: string; name: string; priority: string; feasibility: string; v4Status: string;\n')
    f.write('  phase: string; approach: string; dependency: string; api: string; rules: string; acceptance: string; }\n')
    f.write(f'export const REQUIREMENTS: Requirement[] = {body};\n')
print(len(items), 'requirements written')
