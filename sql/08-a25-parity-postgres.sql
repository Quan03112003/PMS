BEGIN;

ALTER TABLE room_types ADD COLUMN IF NOT EXISTS weekday_rate numeric(18,2);
ALTER TABLE room_types ADD COLUMN IF NOT EXISTS weekend_rate numeric(18,2);
ALTER TABLE room_types ADD COLUMN IF NOT EXISTS hourly_rate numeric(18,2);
ALTER TABLE room_types ADD COLUMN IF NOT EXISTS extra_hour_rate numeric(18,2);
ALTER TABLE room_types ADD COLUMN IF NOT EXISTS extra_person_rate numeric(18,2);

ALTER TABLE guests ADD COLUMN IF NOT EXISTS title character varying(10);
ALTER TABLE guests ADD COLUMN IF NOT EXISTS gender character varying(10);
ALTER TABLE guests ADD COLUMN IF NOT EXISTS id_document_type character varying(20);
ALTER TABLE guests ADD COLUMN IF NOT EXISTS ethnicity character varying(40);
ALTER TABLE guests ADD COLUMN IF NOT EXISTS religion character varying(40);
ALTER TABLE guests ADD COLUMN IF NOT EXISTS stay_purpose character varying(30);
ALTER TABLE guests ADD COLUMN IF NOT EXISTS loyalty_card character varying(30);

CREATE TABLE IF NOT EXISTS housekeeping_tasks (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_id integer NOT NULL,
    room_id integer NOT NULL,
    kind character varying(20) NOT NULL,
    status character varying(20) NOT NULL,
    started_at_utc timestamp with time zone NOT NULL,
    finished_at_utc timestamp with time zone,
    cleaner1 character varying(80),
    cleaner2 character varying(80),
    cleaner3 character varying(80),
    inspector_name character varying(80),
    note character varying(300)
);
CREATE INDEX IF NOT EXISTS "IX_housekeeping_tasks_property_id_status" ON housekeeping_tasks (property_id, status);

CREATE TABLE IF NOT EXISTS desk_notes (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_id integer NOT NULL,
    text character varying(240) NOT NULL,
    status character varying(20) NOT NULL,
    created_by_user_id integer NOT NULL,
    created_at_utc timestamp with time zone NOT NULL
);
CREATE INDEX IF NOT EXISTS "IX_desk_notes_property_id_status" ON desk_notes (property_id, status);

COMMIT;
