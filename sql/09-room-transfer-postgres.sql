-- Room move history. Safe to run more than once on PostgreSQL.
-- Apply this before any deploy that references room_transfer_histories in /api/health/ready.
BEGIN;

CREATE TABLE IF NOT EXISTS room_transfer_histories (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_id integer NOT NULL,
    reservation_id integer NOT NULL,
    stay_id integer NOT NULL,
    old_room_id integer NOT NULL,
    new_room_id integer NOT NULL,
    reason_code character varying(30) NOT NULL,
    reason_note character varying(200),
    old_rate numeric(18,2) NOT NULL,
    new_rate numeric(18,2) NOT NULL,
    rate_delta numeric(18,2) NOT NULL,
    effective_at_utc timestamp with time zone NOT NULL,
    created_by_user_id integer NOT NULL,
    approved_by_user_id integer,
    approved_at_utc timestamp with time zone,
    created_at_utc timestamp with time zone NOT NULL
);
CREATE INDEX IF NOT EXISTS "IX_room_transfer_histories_stay_id_effective_at_utc" ON room_transfer_histories (stay_id, effective_at_utc);

COMMIT;
