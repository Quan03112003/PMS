/**********************************************************************************************
 * LOTUS PMS — OTA channel integration layer — PostgreSQL (Neon) schema upgrade
 * Requirements: YC-OTA-01 (two-layer confirmation), YC-OTA-02 (duplicate review), YC-BS-01 (mapping, sync log)
 *
 * Idempotent: safe to run more than once. Additive only (no DROP, no data rewrite).
 * DDL mirrors what EF Core generates for PmsDbContext with the Npgsql provider.
 * Requires sql/06-v5-foundation-postgres.sql to have been applied first.
 *
 * Run order:
 *   1. Neon: create a branch from production and run this script there first.
 *   2. Verify with the SELECT at the bottom, then run on the production branch.
 *   3. Deploy the backend. /api/health/ready returns 503 until this script has been applied.
 *
 *   psql "$NEON_DATABASE_URL" -v ON_ERROR_STOP=1 -f sql/07-ota-integration-postgres.sql
 **********************************************************************************************/

BEGIN;

CREATE TABLE IF NOT EXISTS channel_connections (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    property_id integer NOT NULL,
    provider character varying(20) NOT NULL,
    display_name character varying(120) NOT NULL,
    hotel_code character varying(60) NOT NULL,
    status character varying(20) NOT NULL,
    created_by_user_id integer NOT NULL,
    created_at_utc timestamp with time zone NOT NULL,
    last_inbound_at_utc timestamp with time zone,
    CONSTRAINT "PK_channel_connections" PRIMARY KEY (id),
    CONSTRAINT "FK_channel_connections_properties_property_id" FOREIGN KEY (property_id) REFERENCES properties (id) ON DELETE RESTRICT
);
CREATE INDEX IF NOT EXISTS "IX_channel_connections_property_id" ON channel_connections (property_id);
CREATE UNIQUE INDEX IF NOT EXISTS "IX_channel_connections_provider_hotel_code" ON channel_connections (provider, hotel_code);

CREATE TABLE IF NOT EXISTS channel_room_mappings (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    connection_id integer NOT NULL,
    property_id integer NOT NULL,
    room_type_id integer NOT NULL,
    channel_room_code character varying(60) NOT NULL,
    channel_rate_code character varying(60) NOT NULL,
    rate_plan_id integer,
    is_active boolean NOT NULL,
    created_at_utc timestamp with time zone NOT NULL,
    CONSTRAINT "PK_channel_room_mappings" PRIMARY KEY (id),
    CONSTRAINT "FK_channel_room_mappings_channel_connections_connection_id" FOREIGN KEY (connection_id) REFERENCES channel_connections (id) ON DELETE RESTRICT,
    CONSTRAINT "FK_channel_room_mappings_properties_property_id" FOREIGN KEY (property_id) REFERENCES properties (id) ON DELETE RESTRICT,
    CONSTRAINT "FK_channel_room_mappings_rate_plans_rate_plan_id" FOREIGN KEY (rate_plan_id) REFERENCES rate_plans (id) ON DELETE RESTRICT,
    CONSTRAINT "FK_channel_room_mappings_room_types_room_type_id" FOREIGN KEY (room_type_id) REFERENCES room_types (id) ON DELETE RESTRICT
);
CREATE UNIQUE INDEX IF NOT EXISTS "IX_channel_room_mappings_connection_id_channel_room_code_chann~" ON channel_room_mappings (connection_id, channel_room_code, channel_rate_code);
CREATE INDEX IF NOT EXISTS "IX_channel_room_mappings_property_id" ON channel_room_mappings (property_id);
CREATE INDEX IF NOT EXISTS "IX_channel_room_mappings_rate_plan_id" ON channel_room_mappings (rate_plan_id);
CREATE INDEX IF NOT EXISTS "IX_channel_room_mappings_room_type_id" ON channel_room_mappings (room_type_id);

-- Raw channel payloads are intentionally not stored; payload_hash identifies replays.
CREATE TABLE IF NOT EXISTS channel_bookings (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    connection_id integer NOT NULL,
    property_id integer NOT NULL,
    provider character varying(20) NOT NULL,
    channel_booking_id character varying(80) NOT NULL,
    event_type character varying(10) NOT NULL,
    payload_hash character varying(64) NOT NULL,
    fingerprint character varying(64) NOT NULL,
    status character varying(30) NOT NULL,
    reservation_id integer,
    related_booking_id integer,
    guest_name character varying(200) NOT NULL,
    phone character varying(30),
    email character varying(160),
    check_in_date date NOT NULL,
    check_out_date date NOT NULL,
    channel_room_code character varying(60) NOT NULL,
    channel_rate_code character varying(60) NOT NULL,
    adults integer NOT NULL,
    children integer NOT NULL,
    total_amount numeric(18,2) NOT NULL,
    currency character varying(3) NOT NULL,
    is_sandbox boolean NOT NULL,
    message character varying(500),
    received_at_utc timestamp with time zone NOT NULL,
    first_confirmed_at_utc timestamp with time zone,
    second_confirmed_at_utc timestamp with time zone,
    second_confirmed_by_user_id integer,
    reviewed_at_utc timestamp with time zone,
    reviewed_by_user_id integer,
    review_note character varying(500),
    CONSTRAINT "PK_channel_bookings" PRIMARY KEY (id),
    CONSTRAINT "FK_channel_bookings_channel_connections_connection_id" FOREIGN KEY (connection_id) REFERENCES channel_connections (id) ON DELETE RESTRICT,
    CONSTRAINT "FK_channel_bookings_properties_property_id" FOREIGN KEY (property_id) REFERENCES properties (id) ON DELETE RESTRICT,
    CONSTRAINT "FK_channel_bookings_reservations_reservation_id" FOREIGN KEY (reservation_id) REFERENCES reservations (id) ON DELETE RESTRICT
);
CREATE INDEX IF NOT EXISTS "IX_channel_bookings_connection_id" ON channel_bookings (connection_id);
CREATE INDEX IF NOT EXISTS "IX_channel_bookings_property_id_fingerprint" ON channel_bookings (property_id, fingerprint);
CREATE INDEX IF NOT EXISTS "IX_channel_bookings_property_id_status" ON channel_bookings (property_id, status);
CREATE UNIQUE INDEX IF NOT EXISTS "IX_channel_bookings_provider_channel_booking_id_payload_hash" ON channel_bookings (provider, channel_booking_id, payload_hash);
CREATE INDEX IF NOT EXISTS "IX_channel_bookings_reservation_id" ON channel_bookings (reservation_id);

CREATE TABLE IF NOT EXISTS channel_sync_logs (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    connection_id integer,
    property_id integer,
    provider character varying(20) NOT NULL,
    direction character varying(10) NOT NULL,
    event_type character varying(30) NOT NULL,
    outcome character varying(20) NOT NULL,
    message character varying(500) NOT NULL,
    channel_booking_record_id integer,
    created_at_utc timestamp with time zone NOT NULL,
    CONSTRAINT "PK_channel_sync_logs" PRIMARY KEY (id),
    CONSTRAINT "FK_channel_sync_logs_channel_connections_connection_id" FOREIGN KEY (connection_id) REFERENCES channel_connections (id) ON DELETE RESTRICT
);
CREATE INDEX IF NOT EXISTS "IX_channel_sync_logs_connection_id" ON channel_sync_logs (connection_id);
CREATE INDEX IF NOT EXISTS "IX_channel_sync_logs_property_id_created_at_utc" ON channel_sync_logs (property_id, created_at_utc);

COMMIT;

-- Verification: expect 4 tables.
SELECT table_name FROM information_schema.tables
 WHERE table_schema = current_schema()
   AND table_name IN ('channel_connections', 'channel_room_mappings', 'channel_bookings', 'channel_sync_logs')
ORDER BY 1;
