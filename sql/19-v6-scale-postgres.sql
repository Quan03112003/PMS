-- V6 local: indexes, package rates, housekeeping assignment, chain snapshots, group master folio.
-- Apply on local Docker before the API readiness check selects these columns.

ALTER TABLE room_types ADD COLUMN IF NOT EXISTS weekly_rate numeric(18,2);
ALTER TABLE room_types ADD COLUMN IF NOT EXISTS monthly_rate numeric(18,2);

ALTER TABLE housekeeping_tasks ADD COLUMN IF NOT EXISTS priority varchar(10) NOT NULL DEFAULT 'NORMAL';
ALTER TABLE housekeeping_tasks ADD COLUMN IF NOT EXISTS shift_code varchar(10) NOT NULL DEFAULT 'MORNING';
ALTER TABLE housekeeping_tasks ADD COLUMN IF NOT EXISTS floor_no integer NOT NULL DEFAULT 0;

CREATE INDEX IF NOT EXISTS ix_folio_charges_reservation_posted ON folio_charges (reservation_id, posted_at_utc);
CREATE INDEX IF NOT EXISTS ix_payments_reservation_paid ON payments (reservation_id, paid_at_utc);
CREATE INDEX IF NOT EXISTS ix_reservations_property_status_in ON reservations (property_id, status, check_in_date);
CREATE INDEX IF NOT EXISTS ix_guests_phone ON guests (phone);
CREATE INDEX IF NOT EXISTS ix_audit_property_time ON audit_events (property_id, occurred_at_utc);

CREATE TABLE IF NOT EXISTS property_day_snapshots (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_id integer NOT NULL REFERENCES properties(id),
    business_date date NOT NULL,
    room_revenue numeric(18,2) NOT NULL DEFAULT 0,
    service_revenue numeric(18,2) NOT NULL DEFAULT 0,
    no_show_revenue numeric(18,2) NOT NULL DEFAULT 0,
    payments numeric(18,2) NOT NULL DEFAULT 0,
    expenses numeric(18,2) NOT NULL DEFAULT 0,
    captured_at_utc timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_property_day UNIQUE (property_id, business_date)
);

CREATE TABLE IF NOT EXISTS group_master_folios (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_id integer NOT NULL REFERENCES properties(id),
    code varchar(30) NOT NULL,
    guest_name varchar(160) NOT NULL,
    status varchar(20) NOT NULL DEFAULT 'OPEN',
    opened_at_utc timestamptz NOT NULL DEFAULT now(),
    closed_at_utc timestamptz,
    CONSTRAINT uq_group_master UNIQUE (property_id, code)
);

CREATE TABLE IF NOT EXISTS group_master_lines (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    folio_id integer NOT NULL REFERENCES group_master_folios(id),
    kind varchar(20) NOT NULL,
    description varchar(200) NOT NULL,
    amount numeric(18,2) NOT NULL,
    created_at_utc timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS group_master_payments (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    folio_id integer NOT NULL REFERENCES group_master_folios(id),
    method varchar(20) NOT NULL,
    amount numeric(18,2) NOT NULL,
    reference varchar(80),
    idempotency_key varchar(80),
    paid_at_utc timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_group_master_pay_key ON group_master_payments (idempotency_key) WHERE idempotency_key IS NOT NULL;
