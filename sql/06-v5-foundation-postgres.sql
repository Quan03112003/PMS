/**********************************************************************************************
 * LOTUS PMS V5 foundation — PostgreSQL (Neon) schema upgrade
 *
 * Idempotent: safe to run more than once. Additive only (no DROP, no data rewrite).
 * DDL mirrors what EF Core generates for PmsDbContext with the Npgsql provider, so a later
 * EF migrations baseline will not see drift.
 *
 * Run order:
 *   1. Neon: create a branch from production (or take a backup) and run this script there first.
 *   2. Verify with the SELECT at the bottom, then run on the production branch.
 *   3. Deploy the backend. /api/health/ready returns 503 until this script has been applied.
 *
 *   psql "$NEON_DATABASE_URL" -v ON_ERROR_STOP=1 -f sql/06-v5-foundation-postgres.sql
 **********************************************************************************************/

BEGIN;

-- properties: IANA time zone per property (business date is computed from it in V5.2)
ALTER TABLE properties ADD COLUMN IF NOT EXISTS time_zone_id character varying(64) NOT NULL DEFAULT 'Asia/Ho_Chi_Minh';
ALTER TABLE properties ALTER COLUMN time_zone_id DROP DEFAULT;

-- reservations: rate plan reference + immutable price snapshot
ALTER TABLE reservations ADD COLUMN IF NOT EXISTS rate_plan_id integer;
ALTER TABLE reservations ADD COLUMN IF NOT EXISTS rate_plan_snapshot jsonb;
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'FK_reservations_rate_plans_rate_plan_id') THEN
        ALTER TABLE reservations ADD CONSTRAINT "FK_reservations_rate_plans_rate_plan_id"
            FOREIGN KEY (rate_plan_id) REFERENCES rate_plans (id) ON DELETE RESTRICT;
    END IF;
END $$;
CREATE INDEX IF NOT EXISTS "IX_reservations_rate_plan_id" ON reservations (rate_plan_id);

-- payments: partial unique index in PostgreSQL syntax (replaces the SQL Server style filter)
CREATE UNIQUE INDEX IF NOT EXISTS "IX_payments_idempotency_key" ON payments (idempotency_key) WHERE idempotency_key IS NOT NULL;

CREATE TABLE IF NOT EXISTS adjustment_vouchers (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    code character varying(30) NOT NULL,
    property_id integer NOT NULL,
    reservation_id integer NOT NULL,
    original_charge_id integer,
    kind character varying(20) NOT NULL,
    amount_delta numeric(18,2) NOT NULL,
    reason character varying(500) NOT NULL,
    status character varying(20) NOT NULL,
    created_by_user_id integer NOT NULL,
    created_at_utc timestamp with time zone NOT NULL,
    approved_by_user_id integer,
    approved_at_utc timestamp with time zone,
    rejected_by_user_id integer,
    rejected_at_utc timestamp with time zone,
    rejection_reason character varying(500),
    posted_by_user_id integer,
    posted_at_utc timestamp with time zone,
    posted_charge_id integer,
    idempotency_key character varying(80) NOT NULL,
    CONSTRAINT "PK_adjustment_vouchers" PRIMARY KEY (id),
    CONSTRAINT "FK_adjustment_vouchers_folio_charges_original_charge_id" FOREIGN KEY (original_charge_id) REFERENCES folio_charges (id) ON DELETE RESTRICT,
    CONSTRAINT "FK_adjustment_vouchers_folio_charges_posted_charge_id" FOREIGN KEY (posted_charge_id) REFERENCES folio_charges (id) ON DELETE RESTRICT,
    CONSTRAINT "FK_adjustment_vouchers_properties_property_id" FOREIGN KEY (property_id) REFERENCES properties (id) ON DELETE RESTRICT,
    CONSTRAINT "FK_adjustment_vouchers_reservations_reservation_id" FOREIGN KEY (reservation_id) REFERENCES reservations (id) ON DELETE RESTRICT
);
CREATE UNIQUE INDEX IF NOT EXISTS "IX_adjustment_vouchers_idempotency_key" ON adjustment_vouchers (idempotency_key);
CREATE INDEX IF NOT EXISTS "IX_adjustment_vouchers_original_charge_id" ON adjustment_vouchers (original_charge_id);
CREATE INDEX IF NOT EXISTS "IX_adjustment_vouchers_posted_charge_id" ON adjustment_vouchers (posted_charge_id);
CREATE UNIQUE INDEX IF NOT EXISTS "IX_adjustment_vouchers_property_id_code" ON adjustment_vouchers (property_id, code);
CREATE INDEX IF NOT EXISTS "IX_adjustment_vouchers_reservation_id_status" ON adjustment_vouchers (reservation_id, status);

CREATE TABLE IF NOT EXISTS tax_rules (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    property_id integer NOT NULL,
    code character varying(30) NOT NULL,
    name character varying(120) NOT NULL,
    tax_type character varying(20) NOT NULL,
    rate_percent numeric(7,4) NOT NULL,
    is_inclusive boolean NOT NULL,
    applies_to character varying(20) NOT NULL,
    effective_from date NOT NULL,
    effective_to date,
    is_active boolean NOT NULL,
    created_by_user_id integer NOT NULL,
    created_at_utc timestamp with time zone NOT NULL,
    CONSTRAINT "PK_tax_rules" PRIMARY KEY (id),
    CONSTRAINT "FK_tax_rules_properties_property_id" FOREIGN KEY (property_id) REFERENCES properties (id) ON DELETE RESTRICT
);
CREATE UNIQUE INDEX IF NOT EXISTS "IX_tax_rules_property_id_code_effective_from" ON tax_rules (property_id, code, effective_from);

CREATE TABLE IF NOT EXISTS holiday_rates (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    property_id integer NOT NULL,
    code character varying(30) NOT NULL,
    name character varying(120) NOT NULL,
    date_from date NOT NULL,
    date_to date NOT NULL,
    adjustment_percent numeric(7,4) NOT NULL,
    is_active boolean NOT NULL,
    created_by_user_id integer NOT NULL,
    created_at_utc timestamp with time zone NOT NULL,
    CONSTRAINT "PK_holiday_rates" PRIMARY KEY (id),
    CONSTRAINT "FK_holiday_rates_properties_property_id" FOREIGN KEY (property_id) REFERENCES properties (id) ON DELETE RESTRICT
);
CREATE UNIQUE INDEX IF NOT EXISTS "IX_holiday_rates_property_id_code" ON holiday_rates (property_id, code);

CREATE TABLE IF NOT EXISTS night_audit_logs (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    property_id integer NOT NULL,
    business_date date NOT NULL,
    status character varying(20) NOT NULL,
    room_charges numeric(18,2) NOT NULL,
    service_charges numeric(18,2) NOT NULL,
    total_payments numeric(18,2) NOT NULL,
    locked_at_utc timestamp with time zone,
    locked_by_user_id integer,
    reopened_at_utc timestamp with time zone,
    reopened_by_user_id integer,
    reopen_reason character varying(500),
    created_at_utc timestamp with time zone NOT NULL,
    CONSTRAINT "PK_night_audit_logs" PRIMARY KEY (id),
    CONSTRAINT "FK_night_audit_logs_properties_property_id" FOREIGN KEY (property_id) REFERENCES properties (id) ON DELETE RESTRICT
);
CREATE UNIQUE INDEX IF NOT EXISTS "IX_night_audit_logs_property_id_business_date" ON night_audit_logs (property_id, business_date);

CREATE TABLE IF NOT EXISTS e_invoices (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    property_id integer NOT NULL,
    reservation_id integer,
    customer_name character varying(200) NOT NULL,
    customer_tax_id character varying(20),
    total_amount numeric(18,2) NOT NULL,
    tax_amount numeric(18,2) NOT NULL,
    status character varying(20) NOT NULL,
    invoice_number character varying(40),
    request_payload jsonb,
    response_payload jsonb,
    created_by_user_id integer NOT NULL,
    created_at_utc timestamp with time zone NOT NULL,
    issued_at_utc timestamp with time zone,
    CONSTRAINT "PK_e_invoices" PRIMARY KEY (id),
    CONSTRAINT "FK_e_invoices_properties_property_id" FOREIGN KEY (property_id) REFERENCES properties (id) ON DELETE RESTRICT,
    CONSTRAINT "FK_e_invoices_reservations_reservation_id" FOREIGN KEY (reservation_id) REFERENCES reservations (id) ON DELETE RESTRICT
);
CREATE INDEX IF NOT EXISTS "IX_e_invoices_property_id_status" ON e_invoices (property_id, status);
CREATE INDEX IF NOT EXISTS "IX_e_invoices_reservation_id" ON e_invoices (reservation_id);

CREATE TABLE IF NOT EXISTS action_permissions (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    role character varying(30) NOT NULL,
    permission_key character varying(80) NOT NULL,
    property_id integer,
    is_allowed boolean NOT NULL,
    CONSTRAINT "PK_action_permissions" PRIMARY KEY (id),
    CONSTRAINT "FK_action_permissions_properties_property_id" FOREIGN KEY (property_id) REFERENCES properties (id) ON DELETE RESTRICT
);
CREATE INDEX IF NOT EXISTS "IX_action_permissions_property_id" ON action_permissions (property_id);
CREATE UNIQUE INDEX IF NOT EXISTS "IX_action_permissions_role_permission_key_property_id" ON action_permissions (role, permission_key, property_id);

COMMIT;

-- Verification: expect 6 tables and 3 columns.
SELECT 'table' AS kind, table_name AS name FROM information_schema.tables
 WHERE table_schema = current_schema()
   AND table_name IN ('adjustment_vouchers', 'tax_rules', 'holiday_rates', 'night_audit_logs', 'e_invoices', 'action_permissions')
UNION ALL
SELECT 'column', table_name || '.' || column_name FROM information_schema.columns
 WHERE table_schema = current_schema()
   AND ((table_name = 'properties' AND column_name = 'time_zone_id')
     OR (table_name = 'reservations' AND column_name IN ('rate_plan_id', 'rate_plan_snapshot')))
ORDER BY 1, 2;
