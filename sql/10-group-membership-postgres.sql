-- Group attach and detach history. Safe to run more than once on PostgreSQL.
-- Apply this before any deploy that references group_membership_events in /api/health/ready.
BEGIN;

CREATE TABLE IF NOT EXISTS group_membership_events (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_id integer NOT NULL,
    reservation_id integer NOT NULL,
    action character varying(20) NOT NULL,
    old_group_code character varying(30),
    new_group_code character varying(30),
    created_by_user_id integer NOT NULL,
    created_at_utc timestamp with time zone NOT NULL
);
CREATE INDEX IF NOT EXISTS "IX_group_membership_events_property_id_new_group_code_created_at_utc"
    ON group_membership_events (property_id, new_group_code, created_at_utc);

COMMIT;
