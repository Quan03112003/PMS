ALTER TABLE guests ADD COLUMN IF NOT EXISTS preferences character varying(300) NULL;

CREATE TABLE IF NOT EXISTS cash_accounts (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  property_id integer NOT NULL REFERENCES properties(id),
  name character varying(80) NOT NULL,
  is_active boolean NOT NULL DEFAULT true,
  created_at_utc timestamp with time zone NOT NULL DEFAULT now(),
  UNIQUE (property_id, name)
);
CREATE TABLE IF NOT EXISTS cash_movements (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  property_id integer NOT NULL REFERENCES properties(id),
  account_id integer NOT NULL REFERENCES cash_accounts(id),
  counter_account_id integer NULL REFERENCES cash_accounts(id),
  movement_type character varying(20) NOT NULL,
  method character varying(20) NOT NULL,
  amount numeric(18,2) NOT NULL,
  note character varying(200) NULL,
  actor_user_id integer NOT NULL,
  created_at_utc timestamp with time zone NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS group_cutoffs (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  property_id integer NOT NULL,
  code character varying(30) NOT NULL,
  cutoff_date date NOT NULL,
  UNIQUE (property_id, code)
);
