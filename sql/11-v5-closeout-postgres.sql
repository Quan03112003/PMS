ALTER TABLE services ADD COLUMN IF NOT EXISTS min_stock integer NOT NULL DEFAULT 0;
ALTER TABLE properties ADD COLUMN IF NOT EXISTS low_occupancy_percent numeric(5,2) NOT NULL DEFAULT 0;
ALTER TABLE properties ADD COLUMN IF NOT EXISTS low_revenue_amount numeric(18,2) NOT NULL DEFAULT 0;

ALTER TABLE folio_charges ADD COLUMN IF NOT EXISTS business_date date NULL;
ALTER TABLE folio_charges ADD COLUMN IF NOT EXISTS night_audit_log_id integer NULL;

ALTER TABLE night_audit_logs ADD COLUMN IF NOT EXISTS rooms_sold integer NOT NULL DEFAULT 0;
ALTER TABLE night_audit_logs ADD COLUMN IF NOT EXISTS rooms_available integer NOT NULL DEFAULT 0;
ALTER TABLE night_audit_logs ADD COLUMN IF NOT EXISTS occupancy_percent numeric(6,2) NOT NULL DEFAULT 0;
ALTER TABLE night_audit_logs ADD COLUMN IF NOT EXISTS adr numeric(18,2) NOT NULL DEFAULT 0;
ALTER TABLE night_audit_logs ADD COLUMN IF NOT EXISTS revpar numeric(18,2) NOT NULL DEFAULT 0;

CREATE TABLE IF NOT EXISTS booking_note_types (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_id integer NULL REFERENCES properties(id) ON DELETE RESTRICT,
    code varchar(40) NOT NULL,
    name varchar(80) NOT NULL,
    is_required boolean NOT NULL DEFAULT false,
    allow_free_text boolean NOT NULL DEFAULT true,
    is_active boolean NOT NULL DEFAULT true,
    sort_order integer NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_booking_note_types_scope_code
    ON booking_note_types (COALESCE(property_id, 0), code);

CREATE TABLE IF NOT EXISTS reservation_notes (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id integer NOT NULL REFERENCES reservations(id) ON DELETE RESTRICT,
    note_type_id integer NOT NULL REFERENCES booking_note_types(id) ON DELETE RESTRICT,
    note_text varchar(500) NOT NULL,
    version integer NOT NULL DEFAULT 1,
    is_current boolean NOT NULL DEFAULT true,
    created_by_user_id integer NOT NULL REFERENCES app_users(id) ON DELETE RESTRICT,
    created_at_utc timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_reservation_notes_current
    ON reservation_notes (reservation_id, note_type_id) WHERE is_current;

CREATE TABLE IF NOT EXISTS reservation_holds (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_id integer NOT NULL REFERENCES properties(id) ON DELETE RESTRICT,
    room_id integer NOT NULL REFERENCES rooms(id) ON DELETE RESTRICT,
    guest_name varchar(150) NOT NULL,
    guest_phone varchar(30) NULL,
    check_in_date date NOT NULL,
    check_out_date date NOT NULL,
    status varchar(20) NOT NULL DEFAULT 'ACTIVE',
    held_at_utc timestamptz NOT NULL DEFAULT now(),
    expires_at_utc timestamptz NOT NULL,
    released_at_utc timestamptz NULL,
    release_reason varchar(200) NULL,
    converted_reservation_id integer NULL REFERENCES reservations(id) ON DELETE RESTRICT,
    created_by_user_id integer NOT NULL REFERENCES app_users(id) ON DELETE RESTRICT,
    idempotency_key varchar(80) NULL
);
CREATE INDEX IF NOT EXISTS ix_reservation_holds_room_status ON reservation_holds (room_id, status, expires_at_utc);
CREATE UNIQUE INDEX IF NOT EXISTS ux_reservation_holds_idem
    ON reservation_holds (idempotency_key) WHERE idempotency_key IS NOT NULL;

CREATE TABLE IF NOT EXISTS housekeeping_task_items (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id integer NOT NULL REFERENCES housekeeping_tasks(id) ON DELETE RESTRICT,
    checklist_code varchar(40) NOT NULL,
    label varchar(120) NOT NULL,
    is_required boolean NOT NULL DEFAULT true,
    is_done boolean NOT NULL DEFAULT false,
    note varchar(200) NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_hk_task_items_code ON housekeeping_task_items (task_id, checklist_code);

CREATE TABLE IF NOT EXISTS housekeeping_task_media (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id integer NOT NULL REFERENCES housekeeping_tasks(id) ON DELETE RESTRICT,
    object_key varchar(240) NOT NULL,
    content_type varchar(80) NOT NULL,
    file_size bigint NOT NULL,
    media_type varchar(20) NOT NULL DEFAULT 'PHOTO',
    uploaded_by_user_id integer NOT NULL REFERENCES app_users(id) ON DELETE RESTRICT,
    uploaded_at_utc timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS night_audit_lines (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    night_audit_log_id integer NOT NULL REFERENCES night_audit_logs(id) ON DELETE RESTRICT,
    reservation_id integer NOT NULL REFERENCES reservations(id) ON DELETE RESTRICT,
    business_date date NOT NULL,
    action varchar(20) NOT NULL,
    amount numeric(18,2) NOT NULL DEFAULT 0,
    folio_charge_id integer NULL REFERENCES folio_charges(id) ON DELETE RESTRICT
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_night_audit_lines_stay_night
    ON night_audit_lines (reservation_id, business_date);

CREATE TABLE IF NOT EXISTS notification_dispatches (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_id integer NOT NULL REFERENCES properties(id) ON DELETE RESTRICT,
    reservation_id integer NOT NULL REFERENCES reservations(id) ON DELETE RESTRICT,
    notification_type varchar(40) NOT NULL,
    milestone varchar(40) NOT NULL,
    channel varchar(20) NOT NULL DEFAULT 'IN_APP',
    status varchar(20) NOT NULL DEFAULT 'LOGGED',
    scheduled_at_utc timestamptz NOT NULL,
    sent_at_utc timestamptz NULL,
    attempt_count integer NOT NULL DEFAULT 1,
    last_error varchar(200) NULL,
    idempotency_key varchar(120) NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_notification_dispatches_key ON notification_dispatches (idempotency_key);

CREATE TABLE IF NOT EXISTS payment_refunds (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_id integer NOT NULL REFERENCES properties(id) ON DELETE RESTRICT,
    reservation_id integer NOT NULL REFERENCES reservations(id) ON DELETE RESTRICT,
    original_payment_id integer NOT NULL REFERENCES payments(id) ON DELETE RESTRICT,
    requested_amount numeric(18,2) NOT NULL,
    approved_amount numeric(18,2) NULL,
    reason_code varchar(40) NOT NULL,
    reason_text varchar(200) NULL,
    status varchar(20) NOT NULL DEFAULT 'PENDING',
    requested_by_user_id integer NOT NULL REFERENCES app_users(id) ON DELETE RESTRICT,
    approved_by_user_id integer NULL REFERENCES app_users(id) ON DELETE RESTRICT,
    requested_at_utc timestamptz NOT NULL DEFAULT now(),
    approved_at_utc timestamptz NULL,
    posted_payment_id integer NULL REFERENCES payments(id) ON DELETE RESTRICT,
    idempotency_key varchar(80) NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_payment_refunds_idem ON payment_refunds (idempotency_key);
