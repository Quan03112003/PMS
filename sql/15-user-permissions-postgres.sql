ALTER TABLE app_users ADD COLUMN IF NOT EXISTS permissions_customized boolean NOT NULL DEFAULT false;
CREATE TABLE IF NOT EXISTS user_permissions (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
    permission_key character varying(80) NOT NULL,
    CONSTRAINT uq_user_permissions UNIQUE (user_id, permission_key)
);
