-- Electronic shift handover. One book per cash shift.
-- Additive only. Safe to re-run. Apply before the API that selects shift_handovers.

CREATE TABLE IF NOT EXISTS shift_handovers (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_id integer NOT NULL REFERENCES properties(id) ON DELETE RESTRICT,
    cash_shift_id integer NOT NULL REFERENCES cash_shifts(id) ON DELETE RESTRICT,
    from_user_id integer NOT NULL REFERENCES app_users(id) ON DELETE RESTRICT,
    to_user_id integer NOT NULL REFERENCES app_users(id) ON DELETE RESTRICT,
    status varchar(20) NOT NULL,
    opening_amount numeric(18,2) NOT NULL,
    expected_cash numeric(18,2) NOT NULL,
    declared_cash numeric(18,2) NOT NULL,
    variance numeric(18,2) NOT NULL,
    note varchar(500) NULL,
    submitted_at_utc timestamptz NOT NULL DEFAULT now(),
    acknowledged_at_utc timestamptz NULL,
    acknowledged_by_user_id integer NULL REFERENCES app_users(id) ON DELETE RESTRICT
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_shift_handovers_shift ON shift_handovers (cash_shift_id);

CREATE TABLE IF NOT EXISTS shift_handover_items (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    handover_id integer NOT NULL REFERENCES shift_handovers(id) ON DELETE RESTRICT,
    kind varchar(24) NOT NULL,
    reference varchar(40) NOT NULL,
    summary varchar(240) NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_shift_handover_items_book ON shift_handover_items (handover_id);

CREATE TABLE IF NOT EXISTS shift_handover_notes (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    handover_id integer NOT NULL REFERENCES shift_handovers(id) ON DELETE RESTRICT,
    author_user_id integer NOT NULL REFERENCES app_users(id) ON DELETE RESTRICT,
    text varchar(500) NOT NULL,
    created_at_utc timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_shift_handover_notes_book ON shift_handover_notes (handover_id);
