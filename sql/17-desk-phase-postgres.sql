ALTER TABLE debt_receivables ALTER COLUMN reservation_id DROP NOT NULL;
ALTER TABLE debt_receivables ADD COLUMN IF NOT EXISTS origin character varying(20) NOT NULL DEFAULT 'CHECKOUT';
ALTER TABLE debt_receivables ADD COLUMN IF NOT EXISTS virtual_folio_id integer NULL;

CREATE TABLE IF NOT EXISTS virtual_folios (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  property_id integer NOT NULL REFERENCES properties(id),
  code character varying(30) NOT NULL UNIQUE,
  guest_name character varying(160) NOT NULL,
  phone character varying(30) NULL,
  note character varying(300) NULL,
  status character varying(20) NOT NULL DEFAULT 'OPEN',
  created_at_utc timestamp with time zone NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS virtual_folio_lines (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  folio_id integer NOT NULL REFERENCES virtual_folios(id) ON DELETE CASCADE,
  service_item_id integer NULL,
  kind character varying(20) NOT NULL,
  description character varying(160) NOT NULL,
  quantity integer NOT NULL,
  unit_price numeric(18,2) NOT NULL,
  amount numeric(18,2) NOT NULL,
  posted_at_utc timestamp with time zone NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS virtual_folio_payments (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  folio_id integer NOT NULL REFERENCES virtual_folios(id) ON DELETE CASCADE,
  amount numeric(18,2) NOT NULL,
  method character varying(20) NOT NULL,
  shift_id integer NULL,
  reference character varying(80) NULL,
  idempotency_key character varying(80) NULL,
  paid_at_utc timestamp with time zone NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_virtual_folio_payment_key ON virtual_folio_payments(idempotency_key) WHERE idempotency_key IS NOT NULL;
